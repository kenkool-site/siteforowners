#!/usr/bin/env node
/**
 * Scans public/defaults/services/<type>/ and writes a static manifest mapping
 * each "<type>/<slug>" to the actual image file that exists on disk (any of
 * .jpg/.jpeg/.png/.webp). This lets default-services.ts resolve a concrete path
 * without touching the filesystem at runtime (it's bundled for the browser).
 *
 * Re-run after adding/replacing/removing default service images:
 *   npm run gen:service-images
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SERVICES_DIR = join(ROOT, "public", "defaults", "services");
const OUT = join(ROOT, "src", "lib", "templates", "service-image-manifest.ts");

// Precedence when a slug has more than one file: PNG (a manual replacement)
// wins over the seeded JPG. Lower index = higher priority.
const EXT_PRIORITY = ["png", "webp", "jpeg", "jpg"];
const IMAGE_RE = /\.(png|webp|jpe?g)$/i;

const types = readdirSync(SERVICES_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const manifest = {};
const duplicates = [];

for (const type of types) {
  const files = readdirSync(join(SERVICES_DIR, type)).filter((f) => IMAGE_RE.test(f));
  const bySlug = new Map();
  for (const file of files) {
    const slug = file.replace(IMAGE_RE, "");
    (bySlug.get(slug) ?? bySlug.set(slug, []).get(slug)).push(file);
  }
  for (const [slug, candidates] of bySlug) {
    candidates.sort(
      (a, b) =>
        EXT_PRIORITY.indexOf(a.split(".").pop().toLowerCase()) -
        EXT_PRIORITY.indexOf(b.split(".").pop().toLowerCase()),
    );
    if (candidates.length > 1) duplicates.push(`${type}/${slug}: ${candidates.join(", ")} (using ${candidates[0]})`);
    manifest[`${type}/${slug}`] = `/defaults/services/${type}/${candidates[0]}`;
  }
}

const entries = Object.keys(manifest)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(manifest[k])},`)
  .join("\n");

const body = `// AUTO-GENERATED by scripts/generate-service-images.mjs — do not edit by hand.
// Maps "<business-type>/<service-slug>" to the actual default image file on disk.
// Re-run \`npm run gen:service-images\` after changing files in
// public/defaults/services/.

export const SERVICE_IMAGE_FILES: Record<string, string> = {
${entries}
};
`;

writeFileSync(OUT, body);
console.log(`Wrote ${Object.keys(manifest).length} entries to ${OUT.replace(ROOT + "/", "")}`);
if (duplicates.length) {
  console.warn(`\n⚠️  ${duplicates.length} slug(s) have multiple files (delete the stale one):`);
  for (const d of duplicates) console.warn(`   ${d}`);
}
